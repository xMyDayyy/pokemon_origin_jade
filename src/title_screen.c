// Creates the four sprites of the Pokemon lettering above the screen.
static void CreateJadeLogoSprites(void)
{
    u32 i;

    // Four 64x64 pieces (centers 21/85/149/213) form the 256x64 lettering;
    // target Y 28 puts the top edge at 8.
    for (i = 0; i < 4; i++)
    {
        u8 id = CreateSprite(&sJadeLogoSpriteTemplate, 21 + i * 64, -40, 0);
        sJadeLogoSpriteIds[i] = id;
        if (id != MAX_SPRITES)
        {
            gSprites[id].oam.tileNum += i * 128;   // 64x64 in 8bpp = 128 tile slots
            gSprites[id].data[0] = 28;
            gSprites[id].data[1] = 0;
        }
    }
}

