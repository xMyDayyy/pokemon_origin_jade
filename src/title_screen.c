static void SpriteCB_VersionBannerLeft(struct Sprite *sprite)
{
    if (gTasks[sprite->sParentTaskId].tSkipToNext)
    {
        sprite->oam.objMode = ST_OAM_OBJ_NORMAL;
        sprite->y = VERSION_BANNER_Y_GOAL;
#if IS_HNS
        sprite->invisible = FALSE;
        sprite->data[2] = JADE_ZOOM_FRAMES;
        sprite->data[3] = 1;
        SetOamMatrix(JADE_ZOOM_MATRIX, 0x100, 0, 0, 0x100);
        sprite->x = VERSION_BANNER_LEFT_X;
#endif
    }
    else
    {
#if IS_HNS
        // Origin Jade: the banner zooms in up to its anchor point, no alpha blend.
        if (sprite->data[3] != 0)
            sprite->x = 120 - JadeZoomStep(sprite);
#else
        if (sprite->y != VERSION_BANNER_Y_GOAL)
            sprite->y++;
        if (sprite->sAlphaBlendIdx != 0)
            sprite->sAlphaBlendIdx--;
        SetGpuReg(REG_OFFSET_BLDALPHA, gTitleScreenAlphaBlend[sprite->sAlphaBlendIdx]);
#endif
    }
}

static void SpriteCB_VersionBannerRight(struct Sprite *sprite)
{
    if (gTasks[sprite->sParentTaskId].tSkipToNext)
    {
        sprite->oam.objMode = ST_OAM_OBJ_NORMAL;
        sprite->y = VERSION_BANNER_Y_GOAL;
#if IS_HNS
        sprite->invisible = FALSE;
        sprite->data[2] = JADE_ZOOM_FRAMES;
        sprite->data[3] = 1;
        sprite->x = VERSION_BANNER_RIGHT_X;
#endif
    }
    else
    {
#if IS_HNS
        if (sprite->data[3] != 0)
            sprite->x = 120 + JadeZoomStep(sprite);
#else
        if (sprite->y != VERSION_BANNER_Y_GOAL)
            sprite->y++;
#endif
    }
}

// Sprite data for SpriteCB_PressStartCopyrightBanner
#define sAnimate data[0]
#define sTimer   data[1]

static void SpriteCB_PressStartCopyrightBanner(struct Sprite *sprite)
{
    if (sprite->sAnimate == TRUE)
    {
        // Alternate between hidden and shown every 16th frame
        if (++sprite->sTimer & 16)
            sprite->invisible = FALSE;
        else
            sprite->invisible = TRUE;
    }
    else
    {
        sprite->invisible = FALSE;
    }
}

static void CreatePressStartBanner(s16 x, s16 y)
{
    u8 i;
    u8 spriteId;

    x -= 64;
    for (i = 0; i < NUM_PRESS_START_FRAMES; i++, x += 32)
    {
        spriteId = CreateSprite(&sStartCopyrightBannerSpriteTemplate, x, y, 0);
        StartSpriteAnim(&gSprites[spriteId], i);
        gSprites[spriteId].sAnimate = TRUE;
    }
}

