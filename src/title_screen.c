#if IS_HNS
// Origin Jade: lightning animation. Each beam color slot flashes white on its
// own cycle (strike, decay, rest).
static u16 JadeZuWeiss(u16 basis, u32 wQ8)
{
    u32 r = (basis & 31);
    u32 g = ((basis >> 5) & 31);
    u32 b = ((basis >> 10) & 31);
    r += ((31 - r) * wQ8) >> 8;
    g += ((31 - g) * wQ8) >> 8;
    b += ((31 - b) * wQ8) >> 8;
    return RGB(r, g, b);
}

// Advances the lightning animation by one frame.
static void UpdateJadeTitleAnimation(u8 frameNum)
{
    u32 i;

    if (gPaletteFade.active)
        return;
    if ((frameNum % 2) != 0)
        return;
    for (i = 0; i < ARRAY_COUNT(sJadeStrahlen); i++)
    {
        u32 phase = ((u32)frameNum + i * 53) % 112;
        u32 w;
        u16 farbe;
        if (phase < 4)
            w = 255;                       // strike: bright white
        else if (phase < 22)
            w = 255 - (phase - 4) * 14;    // quick decay
        else
            w = 0;                         // rest: base color
        farbe = JadeZuWeiss(sJadeStrahlen[i].farbe, w);
        LoadPalette(&farbe, sJadeStrahlen[i].slot, sizeof(farbe));
    }
}
#endif

static void UpdateLegendaryMarkingColor(u8 frameNum)
{
#if IS_HNS
    // Origin Jade: lightning animation, off. Set to TRUE to enable; timing in UpdateJadeTitleAnimation.
    #define JADE_TITEL_ANIMATION FALSE
    if (JADE_TITEL_ANIMATION)
        UpdateJadeTitleAnimation(frameNum);
    return;
#endif
    if ((frameNum % 4) == 0) // Change color every 4th frame
    {
        s32 intensity = Cos(frameNum, Q_8_8(0.5)) + Q_8_8(0.5);
        u32 r = 31 - Q_8_8_TO_INT(intensity * 31);
        u32 g = 31 - Q_8_8_TO_INT(intensity * 22);
        u32 b = 12;

        u16 color = RGB(r, g, b);
        LoadPalette(&color, BG_PLTT_ID(14) + 15, sizeof(color));
   }
}
